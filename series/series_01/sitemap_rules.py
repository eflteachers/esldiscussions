"""
sitemap_rules.py
────────────────
Site-specific rules for discovering lesson URLs on esldiscussions.com.

Discovery reality for this site (verified):

* ``/sitemap.xml`` and every other common path return HTTP 403, but the
  GZIPPED sitemap at ``/sitemap.xml.gz`` returns HTTP 200 and is a valid
  urlset (674 entries, generated by iGooMap).
* That sitemap is STALE: every ``<lastmod>`` is ``2016-02-16``, which is the
  generation date of the file rather than a per-lesson publish date, and it
  misses ~24 lessons added to the site after 2016 (russia, palestine,
  cannabis, drones, the month lessons, job-interviews, ...).
* Lesson pages themselves carry no publish date.

Therefore discovery is a UNION of two sources — sitemap first (per the RF
guidelines' priority order), homepage second to pick up post-2016 lessons —
and the ``date`` field falls back to today for every lesson.

All lesson URLs follow: https://esldiscussions.com/{letter}/{topic}.html
(plus the ``grammar/`` and ``idioms/`` sections, which use the same shape.)

These rules are consumed by sitemap_scraper.py.
"""

import re

# Base site URL
BASE_URL = "https://esldiscussions.com"

# Gzipped sitemap — the only sitemap path that is not 403 on this host.
SITEMAP_GZ_URL = f"{BASE_URL}/sitemap.xml.gz"

# Only URLs matching this pattern are treated as lessons.
# e.g. /a/abortion.html, /z/zambia.html, /grammar/-ed-ing-adjectives.html
LESSON_URL_PATTERN = re.compile(
    r"^https://esldiscussions\.com/[a-z0-9_\-]+/[a-z0-9_\-]+\.html$"
)

# Utility / non-lesson pages to exclude explicitly.
# The first four appear on the homepage; ideas.html and sean_banville.html only
# appear in the sitemap.
EXCLUDE_PATHS = {
    "/",
    "/index.html",
    "/copyright.html",
    "/privacy.html",
    "/links.html",
    "/ideas.html",
    "/sean_banville.html",
    "/faqs.html",
    "/book.html",
    "/help.html",
}

# The sitemap's <lastmod> is the file's generation date, identical for every
# entry, so it must NOT be used as the lesson publish date.
SITEMAP_LASTMOD_IS_RELIABLE = False

# This site provides no usable publish dates → sitemap_scraper falls back to today.
HAS_PUBLISH_DATES = False


def normalise_url(url: str) -> str:
    """
    Canonicalise a discovered URL to the form used in urls.txt and the DB.

    The sitemap still uses the legacy ``http://www.`` prefix; the live site
    serves ``https://`` without ``www``.
    """
    url = url.strip()
    url = re.sub(r"^http://", "https://", url)
    url = re.sub(r"^https://www\.", "https://", url)
    return url


def is_lesson_url(url: str) -> bool:
    """True when the URL is a lesson page and not a utility page."""
    if not LESSON_URL_PATTERN.match(url):
        return False
    path = url[len(BASE_URL):]
    return path not in EXCLUDE_PATHS
